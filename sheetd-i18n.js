export function normalizeLanguage(language = "") {
  return language === "jp" ? "jp" : DEFAULT_LANGUAGE;
}

function readLocalStorageValue(key) {
  try {
    return window.localStorage.getItem(key) || "";
  } catch (_error) {
    return "";
  }
}

function writeLocalStorageValue(key, value) {
  try {
    window.localStorage.setItem(key, value);
  } catch (_error) {
    // Local storage can be unavailable in restricted extension contexts.
  }
}

function hasExplicitLanguageChoice() {
  return Boolean(readLocalStorageValue(LANGUAGE_STORAGE_KEY));
}

function normalizeSalesforceLanguage(language = "") {
  const normalized = String(language || "").trim().toLowerCase().replace("-", "_");
  if (!normalized) {
    return "";
  }
  return normalized.startsWith("ja") || normalized.startsWith("jp") ? "jp" : DEFAULT_LANGUAGE;
}

export function getLanguage() {
  const explicitLanguage = readLocalStorageValue(LANGUAGE_STORAGE_KEY);
  if (explicitLanguage) {
    return normalizeLanguage(explicitLanguage);
  }

  const salesforceLanguage = readLocalStorageValue(SALESFORCE_LANGUAGE_STORAGE_KEY);
  if (salesforceLanguage) {
    return normalizeLanguage(salesforceLanguage);
  }

  const browserLang = (navigator.language || navigator.languages?.[0] || "").toLowerCase();
  return browserLang.startsWith("ja") ? "jp" : DEFAULT_LANGUAGE;
}

export function setLanguage(language) {
  const nextLanguage = normalizeLanguage(language);
  writeLocalStorageValue(LANGUAGE_STORAGE_KEY, nextLanguage);
  applyI18n(document);
  syncLanguageSelectors();
  window.dispatchEvent(new CustomEvent("app-language-change", { detail: { language: nextLanguage } }));
}

export function setSalesforceDefaultLanguage(language) {
  const nextLanguage = normalizeSalesforceLanguage(language);
  if (!nextLanguage) {
    return;
  }

  writeLocalStorageValue(SALESFORCE_LANGUAGE_STORAGE_KEY, nextLanguage);
  if (hasExplicitLanguageChoice()) {
    return;
  }

  applyI18n(document);
  syncLanguageSelectors();
  window.dispatchEvent(new CustomEvent("app-language-change", {
    detail: {
      language: nextLanguage,
      source: "salesforce"
    }
  }));
}

export function t(key, replacements = {}) {
  const language = getLanguage();
  const text = LABELS[language]?.[key] ?? LABELS[DEFAULT_LANGUAGE]?.[key] ?? key;
  return Object.entries(replacements).reduce(
    (nextText, [name, value]) => nextText.replaceAll(`{${name}}`, String(value)),
    text
  );
}

function setTextFromKey(element, attributeName) {
  const key = element.getAttribute(attributeName);
  if (!key) {
    return;
  }
  element.textContent = t(key);
}

function setAttributeFromKey(element, sourceAttribute, targetAttribute) {
  const key = element.getAttribute(sourceAttribute);
  if (!key) {
    return;
  }
  element.setAttribute(targetAttribute, t(key));
}

export function applyI18n(root = document) {
  const language = getLanguage();
  document.documentElement.lang = language === "jp" ? "ja" : "en";
  root.querySelectorAll("[data-i18n]").forEach((element) => setTextFromKey(element, "data-i18n"));
  root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => setAttributeFromKey(element, "data-i18n-placeholder", "placeholder"));
  root.querySelectorAll("[data-i18n-title]").forEach((element) => setAttributeFromKey(element, "data-i18n-title", "title"));
  root.querySelectorAll("[data-i18n-aria-label]").forEach((element) => setAttributeFromKey(element, "data-i18n-aria-label", "aria-label"));
  root.querySelectorAll("[data-i18n-document-title]").forEach((element) => {
    document.title = t(element.getAttribute("data-i18n-document-title"));
  });
}

function syncLanguageSelectors() {
  document.querySelectorAll("[data-language-select]").forEach((select) => {
    select.value = getLanguage();
  });
}

function placeLanguagePicker(target, wrapper) {
  const rowAnchor =
    target.querySelector(".eyebrow") ||
    target.querySelector(".current-tab-title") ||
    target.querySelector(".title");

  if (!rowAnchor) {
    target.prepend(wrapper);
    return;
  }

  let row = Array.from(target.children).find((child) => child.classList.contains("hero-eyebrow-row"));
  if (!row) {
    row = document.createElement("div");
    row.className = "hero-eyebrow-row";
    target.prepend(row);
  }

  if (rowAnchor.parentElement !== row) {
    row.prepend(rowAnchor);
  }
  row.appendChild(wrapper);
}

function createLanguageIcon() {
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.classList.add("app-language-icon");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("focusable", "false");
  [
    ["circle", { cx: "12", cy: "12", r: "10" }],
    ["path", { d: "M2 12h20" }],
    ["path", { d: "M12 2a15.3 15.3 0 0 1 0 20" }],
    ["path", { d: "M12 2a15.3 15.3 0 0 0 0 20" }]
  ].forEach(([tagName, attributes]) => {
    const shape = document.createElementNS("http://www.w3.org/2000/svg", tagName);
    Object.entries(attributes).forEach(([name, value]) => shape.setAttribute(name, value));
    svg.appendChild(shape);
  });
  return svg;
}

export function mountLanguageSelect(target = document.querySelector(".hero")) {
  if (!target || target.querySelector(".app-language-picker")) {
    return null;
  }

  const wrapper = document.createElement("div");
  wrapper.className = "app-language-picker";
  wrapper.dataset.i18nTitle = "language.label";
  wrapper.setAttribute("title", t("language.label"));

  const select = document.createElement("select");
  select.dataset.languageSelect = "true";
  select.dataset.i18nAriaLabel = "language.label";
  select.setAttribute("aria-label", t("language.label"));
  [
    ["en", "language.en"],
    ["jp", "language.jp"]
  ].forEach(([value, labelKey]) => {
    const option = document.createElement("option");
    option.value = value;
    option.dataset.i18n = labelKey;
    option.textContent = t(labelKey);
    select.appendChild(option);
  });
  select.value = getLanguage();
  select.addEventListener("change", () => setLanguage(select.value));
  wrapper.appendChild(createLanguageIcon());
  wrapper.appendChild(select);

  placeLanguagePicker(target, wrapper);
  applyI18n(wrapper);
  return wrapper;
}

export function initI18nPage({ languageTarget = document.querySelector(".hero") } = {}) {
  applyI18n(document);
  mountLanguageSelect(languageTarget);
}

function registerExtensionPageTab() {
  if (location.protocol !== "chrome-extension:" || window.top !== window || !globalThis.chrome?.runtime?.sendMessage) {
    return;
  }
  try {
    const pending = chrome.runtime.sendMessage({ type: "register-extension-page-tab" });
    pending?.catch?.(() => {});
  } catch (_error) {
    // Registration is best-effort; page functionality must not depend on side-panel APIs.
  }
}

registerExtensionPageTab();

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", () => initI18nPage(), { once: true });
} else {
  initI18nPage();
}

window.addEventListener("salesforce-user-language-detected", (event) => {
  setSalesforceDefaultLanguage(event.detail?.language || event.detail?.locale || "");
});
